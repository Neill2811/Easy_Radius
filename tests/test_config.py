from datetime import datetime, timezone

from easy_radius.configgen import (
    parse_clients_conf,
    parse_users_file,
    render_clients_conf,
    render_users_file,
    sanitise_client_name,
)

WHEN = datetime(2026, 1, 2, 3, 4, 5, tzinfo=timezone.utc)
LOCALHOST = "example-localhost-secret"


def test_clients_round_trip_preserves_secrets_and_duplicate_sites():
    routers = [
        {
            "site_name": "ExampleSite",
            "ip": "192.0.2.10",
            "secret": 'quote"and\\slash',
        },
        {
            "site_name": "ExampleSite",
            "ip": "192.0.2.11",
            "secret": "second-example-secret",
        },
        {
            "site_name": "Example Site",
            "ip": "2001:db8::10",
            "secret": "v6-example-secret",
        },
    ]
    text = render_clients_conf(LOCALHOST, routers, when=WHEN)
    parsed = parse_clients_conf(text)

    assert parsed["localhost_secret"] == LOCALHOST
    assert [item["client_name"] for item in parsed["clients"][:2]] == [
        "localhost",
        "localhost_ipv6",
    ]
    assert len(parsed["routers"]) == 3
    assert parsed["routers"][0]["secret"] == 'quote"and\\slash'
    assert parsed["routers"][0]["site_name"] == "ExampleSite"
    assert parsed["routers"][0]["ip"] == "192.0.2.10"
    assert parsed["routers"][1]["secret"] == "second-example-secret"
    assert parsed["routers"][0]["client_name"] != parsed["routers"][1]["client_name"]
    assert parsed["routers"][2]["ip"] == "2001:db8::10"
    assert "ipv6addr = 2001:db8::10" in text
    assert "nas_type = mikrotik" in text
    assert text.count("client localhost {") == 1


def test_clients_exact_block_and_empty_router_list():
    text = render_clients_conf(LOCALHOST, [], when=WHEN)
    expected = """# Generated by Easy Radius. This file is replaced when you click Apply.
# The localhost client is for radtest on this server. It is not a site router.
# Last written: 2026-01-02T03:04:05Z

client localhost {
    ipaddr = 127.0.0.1
    secret = "example-localhost-secret"
    shortname = "localhost"
    nas_type = other
    require_message_authenticator = no
}

client localhost_ipv6 {
    ipv6addr = ::1
    secret = "example-localhost-secret"
    shortname = "localhost"
    nas_type = other
    require_message_authenticator = no
}
"""
    assert text == expected
    parsed = parse_clients_conf(text)
    assert parsed["routers"] == []
    assert parsed["localhost_secret"] == LOCALHOST


def test_users_exact_format_and_round_trip():
    from easy_radius.userhash import hash_user_password

    alice = hash_user_password('pa"ss\\word', salt="examplesalt1234")
    bob = hash_user_password("example-password", salt="examplesalt1234")
    cara = hash_user_password("read-example", salt="examplesalt1234")
    users = [
        {"username": "alice", "password": alice, "group": "write"},
        {"username": "bob", "password": bob, "group": "full"},
        {"username": "cara", "password": cara, "group": "read"},
    ]
    text = render_users_file(users, when=WHEN)
    assert text == (
        "# Generated by Easy Radius. This file is replaced when you click Apply.\n"
        "# Last written: 2026-01-02T03:04:05Z\n"
        "\n"
        f'alice Crypt-Password := "{alice}"\n'
        '    Mikrotik-Group = "write"\n'
        "\n"
        f'bob Crypt-Password := "{bob}"\n'
        '    Mikrotik-Group = "full"\n'
        "\n"
        f'cara Crypt-Password := "{cara}"\n'
        '    Mikrotik-Group = "read"\n'
    )
    assert "Cleartext-Password" not in text
    assert "example-password" not in text
    assert parse_users_file(text) == users


def test_regenerating_users_drops_removed_entries_only():
    first = render_users_file(
        [{"username": "alice", "password": "example-password", "group": "write"}],
        when=WHEN,
    )
    second = render_users_file([], when=WHEN)
    assert "alice" in first
    assert "Crypt-Password" in first
    assert "example-password" not in first
    assert "alice" not in second
    assert parse_users_file(second) == []


def test_client_name_collision_gets_a_suffix():
    taken = {"examplesite_192_0_2_10", "localhost"}
    name = sanitise_client_name("ExampleSite", "192.0.2.10", taken)
    assert name == "examplesite_192_0_2_10_2"
