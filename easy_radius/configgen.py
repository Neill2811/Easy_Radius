"""Generate FreeRADIUS clients.conf and users files.

Easy Radius owns these files. Apply replaces them with the generated text.
The localhost client is always included so radtest can run on this server.
"""

from __future__ import annotations

import ipaddress
import re
from datetime import datetime, timezone

from easy_radius.userhash import hash_user_password, is_nt_hash, is_sha512_crypt, nt_hash

GROUPS = ("full", "write", "read")
_CLIENT_NAME = re.compile(r"[^A-Za-z0-9_]+")


class ConfigError(Exception):
    pass


def escape_radius_string(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def unescape_radius_string(value: str) -> str:
    out: list[str] = []
    i = 0
    while i < len(value):
        if value[i] == "\\" and i + 1 < len(value):
            out.append(value[i + 1])
            i += 2
        else:
            out.append(value[i])
            i += 1
    return "".join(out)


def sanitise_client_name(site_name: str, ip: str, taken: set[str] | None = None) -> str:
    raw = f"{site_name}_{ip}".lower()
    name = _CLIENT_NAME.sub("_", raw).strip("_")
    name = re.sub(r"_+", "_", name)
    if not name or name[0].isdigit():
        name = f"router_{name}" if name else "router"
    reserved = {"localhost", "localhost_ipv6"}
    used = set(taken or ()) | reserved
    candidate = name
    suffix = 2
    while candidate in used:
        candidate = f"{name}_{suffix}"
        suffix += 1
    return candidate


def _quote(value: str) -> str:
    return '"' + escape_radius_string(value) + '"'


def render_clients_conf(localhost_secret: str, routers: list[dict], when: datetime | None = None) -> str:
    if not localhost_secret:
        raise ConfigError("localhost secret is missing")
    stamp = (when or datetime.now(timezone.utc)).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines = [
        "# Generated by Easy Radius. This file is replaced when you click Apply.",
        "# The localhost client is for radtest on this server. It is not a site router.",
        f"# Last written: {stamp}",
        "",
        "client localhost {",
        "    ipaddr = 127.0.0.1",
        f"    secret = {_quote(localhost_secret)}",
        '    shortname = "localhost"',
        "    nas_type = other",
        "    require_message_authenticator = no",
        "}",
        "",
        "client localhost_ipv6 {",
        "    ipv6addr = ::1",
        f"    secret = {_quote(localhost_secret)}",
        '    shortname = "localhost"',
        "    nas_type = other",
        "    require_message_authenticator = no",
        "}",
    ]
    taken = {"localhost", "localhost_ipv6"}
    for router in routers:
        client_name = str(router.get("client_name") or "")
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", client_name) or client_name in taken:
            client_name = sanitise_client_name(router["site_name"], router["ip"], taken)
        taken.add(client_name)
        if router.get("enabled", True) is False:
            continue
        ip = ipaddress.ip_address(router["ip"])
        ip_key = "ipv6addr" if isinstance(ip, ipaddress.IPv6Address) else "ipaddr"
        lines.extend(
            [
                "",
                f"client {client_name} {{",
                f"    {ip_key} = {ip.compressed}",
                f"    secret = {_quote(router['secret'])}",
                f"    shortname = {_quote(router['site_name'])}",
                "    nas_type = mikrotik",
                "    require_message_authenticator = no",
                "}",
            ]
        )
    lines.append("")
    return "\n".join(lines)


def render_users_file(users: list[dict], when: datetime | None = None) -> str:
    stamp = (when or datetime.now(timezone.utc)).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines = [
        "# Generated by Easy Radius. This file is replaced when you click Apply.",
        f"# Last written: {stamp}",
        "",
    ]
    for user in users:
        if user.get("enabled", True) is False:
            continue
        group = user["group"]
        if group not in GROUPS:
            raise ConfigError(f"Unsupported group: {group}")
        username = user["username"]
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.@+-]*", username):
            raise ConfigError(f"Unsupported username: {username}")
        stored = str(user.get("password") or "")
        nt = str(user.get("nt_password") or "")
        if not stored:
            raise ConfigError(f"Missing password hash for {username}")
        if not is_sha512_crypt(stored):
            if not is_nt_hash(nt):
                nt = nt_hash(stored)
            stored = hash_user_password(stored)
        check = f"{username} Crypt-Password := {_quote(stored)}"
        if is_nt_hash(nt):
            check += f", NT-Password := 0x{nt.upper()}"
        lines.append(check)
        lines.append(f'    Mikrotik-Group = "{group}"')
        lines.append("")
    if not users:
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def _unquote_value(raw: str) -> str:
    value = raw.strip()
    if len(value) >= 2 and value[0] == '"' and value[-1] == '"':
        return unescape_radius_string(value[1:-1])
    return value


def parse_clients_conf(text: str) -> dict:
    """Parse a file produced by render_clients_conf."""
    clients: list[dict] = []
    pattern = re.compile(r"\bclient\s+([A-Za-z0-9_]+)\s*\{", re.MULTILINE)
    pos = 0
    while True:
        match = pattern.search(text, pos)
        if not match:
            break
        name = match.group(1)
        start = match.end()
        depth = 1
        index = start
        while index < len(text) and depth:
            char = text[index]
            if char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
            index += 1
        body = text[start : index - 1]
        fields: dict[str, str] = {}
        nested = 0
        for line in body.splitlines():
            if nested == 0:
                assignment = re.match(r"\s*([A-Za-z0-9_-]+)\s*=\s*(.*?)\s*$", line)
                if assignment and "{" not in line:
                    fields[assignment.group(1)] = _unquote_value(assignment.group(2))
            nested += line.count("{") - line.count("}")
            if nested < 0:
                nested = 0
        ip = fields.get("ipaddr") or fields.get("ipv6addr") or ""
        clients.append(
            {
                "client_name": name,
                "ip": ip,
                "secret": fields.get("secret", ""),
                "shortname": fields.get("shortname", ""),
                "nas_type": fields.get("nas_type", ""),
            }
        )
        pos = index
    localhost = [c for c in clients if c["client_name"] == "localhost"]
    routers = [c for c in clients if c["client_name"] not in {"localhost", "localhost_ipv6"}]
    return {
        "localhost_secret": localhost[0]["secret"] if localhost else "",
        "clients": clients,
        "routers": [
            {
                "client_name": c["client_name"],
                "site_name": c["shortname"],
                "ip": c["ip"],
                "secret": c["secret"],
            }
            for c in routers
        ],
    }


def parse_users_file(text: str) -> list[dict]:
    """Parse a users file produced by render_users_file."""
    users: list[dict] = []
    lines = text.splitlines()
    index = 0
    user_re = re.compile(
        r'^(?P<user>[A-Za-z0-9][A-Za-z0-9_.@+-]*)\s+'
        r'(?:Cleartext-Password|Crypt-Password)\s+:=\s+"(?P<pw>.*)"'
        r'(?:,\s*NT-Password\s+:=\s+0x(?P<nt>[0-9A-Fa-f]{32}))?\s*$'
    )
    group_re = re.compile(r'^\s+Mikrotik-Group\s+=\s+"(full|write|read)"\s*$')
    while index < len(lines):
        line = lines[index]
        if not line.strip() or line.lstrip().startswith("#"):
            index += 1
            continue
        match = user_re.match(line)
        if not match:
            raise ConfigError(f"Unrecognised users line: {line}")
        if index + 1 >= len(lines):
            raise ConfigError(f"Missing Mikrotik-Group for {match.group('user')}")
        group_match = group_re.match(lines[index + 1])
        if not group_match:
            raise ConfigError(f"Missing Mikrotik-Group for {match.group('user')}")
        parsed = {
            "username": match.group("user"),
            "password": unescape_radius_string(match.group("pw")),
            "group": group_match.group(1),
        }
        if match.group("nt"):
            parsed["nt_password"] = match.group("nt").upper()
        users.append(parsed)
        index += 2
    return users


def rewrite_cleartext_passwords(text: str) -> str:
    """Turn Cleartext-Password lines into Crypt-Password hashes.

    Lines that are already Crypt-Password are left as they are.
    """
    user_re = re.compile(
        r'^([A-Za-z0-9][A-Za-z0-9_.@+-]*)\s+Cleartext-Password\s+:=\s+"(.*)"\s*$'
    )
    changed = False
    out: list[str] = []
    for line in text.splitlines():
        match = user_re.match(line)
        if not match:
            out.append(line)
            continue
        plain = unescape_radius_string(match.group(2))
        stored = hash_user_password(plain)
        nt = nt_hash(plain)
        out.append(f"{match.group(1)} Crypt-Password := {_quote(stored)}, NT-Password := 0x{nt}")
        changed = True
    if not changed:
        return text
    body = "\n".join(out)
    if text.endswith("\n"):
        body += "\n"
    return body
